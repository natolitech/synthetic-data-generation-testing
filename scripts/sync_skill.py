#!/usr/bin/env python3
"""
sync_skill.py — regenerate the self-contained skill scripts from canonical sources
==================================================================================
The Claude Code skill (``synth-data-gen/``) must work without this repo's Python
path, so it carries a *generated* copy of the ``synthgen`` package plus thin CLI
shims. Never edit those by hand — edit ``synthgen/`` and run:

    make sync-skill            # regenerate
    make check-sync            # verify no drift (used by CI)

The skill's SKILL.md, references/, validate_synthetic.py, and
example_patient_generator.py are copied verbatim from their canonical sources.
"""

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "synth-data-gen"
SCRIPTS = SKILL / "scripts"

GENERATED = "# Generated by scripts/sync_skill.py — do not edit; edit synthgen/ and re-run make sync-skill\n"

SHIMS = {
    "clinical_notes.py": '''#!/usr/bin/env python3
"""{banner}Clinical notes & dictation generator CLI (canonical: synthgen.notes)."""
import sys

from synthgen.notes import main

if __name__ == "__main__":
    sys.exit(main())
''',
    "clinical_bundle.py": '''#!/usr/bin/env python3
"""{banner}Linked clinical bundle CLI (canonical: synthgen.bundle)."""
import sys

from synthgen.bundle import main

if __name__ == "__main__":
    sys.exit(main())
''',
    "generate_from_schema.py": '''#!/usr/bin/env python3
"""{banner}Schema-driven generator CLI (canonical: synthgen.schema_cli).

Usage:
    python generate_from_schema.py schema/ --rows 100 --validate
    python generate_from_schema.py schema/ --list-tables
"""
import sys

from synthgen.schema_cli import main

if __name__ == "__main__":
    sys.exit(main())
''',
}

# verbatim copies from root -> skill
VERBATIM = [
    ("validate_synthetic.py", "validate_synthetic.py"),
    ("example_patient_generator.py", "example_patient_generator.py"),
]

# files that used to be hand-synced copies; superseded by the package
STALE = ["fhir_export.py", "hl7_export.py"]


def sync(check: bool) -> int:
    drift = []

    # 1) package copy
    dest_pkg = SCRIPTS / "synthgen"
    if dest_pkg.exists():
        shutil.rmtree(dest_pkg)
    shutil.copytree(ROOT / "synthgen", dest_pkg,
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    for f in dest_pkg.rglob("*.py"):
        text = f.read_text(encoding="utf-8")
        if not text.startswith("# Generated"):
            f.write_text(GENERATED + text, encoding="utf-8")

    # 2) CLI shims
    for name, template in SHIMS.items():
        content = template.format(banner=GENERATED)
        target = SCRIPTS / name
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                drift.append(name)
        else:
            target.write_text(content, encoding="utf-8")

    # 3) verbatim copies
    for src_name, dst_name in VERBATIM:
        src = (ROOT / src_name).read_text(encoding="utf-8")
        target = SCRIPTS / dst_name
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != src:
                drift.append(dst_name)
        else:
            target.write_text(src, encoding="utf-8")

    # 4) remove files superseded by the package copy
    for name in STALE:
        target = SCRIPTS / name
        if check:
            if target.exists():
                drift.append(f"{name} (stale copy still present)")
        elif target.exists():
            target.unlink()
            print(f"  removed stale copy: {name}")

    if check:
        if drift:
            print("DRIFT DETECTED in skill copies:", ", ".join(drift))
            print("Run: make sync-skill")
            return 1
        print("skill copies in sync")
        return 0

    print(f"synced skill scripts → {SCRIPTS}")
    print("  package: synthgen/ ({} files)".format(
        len(list(dest_pkg.rglob('*.py')))))
    print("  shims:  " + ", ".join(SHIMS))
    print("  verbatim: " + ", ".join(n for n, _ in VERBATIM))
    return 0


if __name__ == "__main__":
    sys.exit(sync(check="--check" in sys.argv))
