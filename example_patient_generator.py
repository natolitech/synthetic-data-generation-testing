#!/usr/bin/env python3
"""
Example: Synthetic Patient Data Generator
==========================================
Generated by synth-data-gen skill.
All data is entirely fictional. No real PII/PHI is used or referenced.

Usage:
    python example_patient_generator.py --rows 100 --seed 42 --format csv
    python example_patient_generator.py --rows 500 --seed 42 --format json
    python example_patient_generator.py --rows 50 --seed 42 --format sql --validate

Dependencies:
    pip install faker pandas
"""

import argparse
import json
import random
import subprocess
import sys
from datetime import date, timedelta
from pathlib import Path

try:
    from faker import Faker
    import pandas as pd
except ImportError:
    print("Missing dependencies. Install with: pip install faker pandas")
    sys.exit(1)


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

SAFE_SSN_PREFIX = "987-65"  # IRS test range
SAFE_EMAIL_DOMAINS = ["example.com", "example.org", "test.invalid"]
SAFE_PHONE_PREFIX = "555-01"

LANGUAGES = [
    ("English", 0.70), ("Spanish", 0.15), ("Mandarin", 0.05),
    ("Arabic", 0.03), ("Tagalog", 0.02), ("Korean", 0.02),
    ("Hindi", 0.01), ("French", 0.01), ("Vietnamese", 0.01),
]

RACE_OPTIONS = [
    ("White", 0.58), ("Black or African American", 0.13),
    ("Asian", 0.12), ("Two or More Races", 0.08),
    ("American Indian or Alaska Native", 0.02),
    ("Native Hawaiian or Other Pacific Islander", 0.01),
    ("Unknown", 0.06),
]

# Names that stress-test parsers
EDGE_CASE_NAMES = [
    ("María", "García-López"),
    ("James", "O'Brien"),
    ("Sœren", "Müller-Björk"),
    ("李", "王小明"),
    ("Александр", "Čapek"),
    ("J", "de la Cruz"),
    ("Mohammed bin Rashid", "Al-Maktoum"),
    ("Mary Anne Elizabeth", "van der Berg-Smithington III"),
]


def weighted_choice(options):
    """Pick from list of (value, weight) tuples."""
    values, weights = zip(*options)
    return random.choices(values, weights=weights, k=1)[0]


def generate_patients(n, fake, seed):
    """Generate n synthetic patient records."""
    patients = []

    # Reserve ~8% of slots for edge-case names
    edge_case_indices = set(random.sample(range(n), min(len(EDGE_CASE_NAMES), max(1, n // 12))))

    for i in range(n):
        pid = f"SYN-{i + 1:06d}"
        mrn = f"MRN-{2240001 + i}"

        # Name
        if i in edge_case_indices:
            idx = list(edge_case_indices).index(i) % len(EDGE_CASE_NAMES)
            first_name, last_name = EDGE_CASE_NAMES[idx]
        else:
            first_name = fake.first_name()
            last_name = fake.last_name()

        # Demographics
        gender = random.choices(
            ["Female", "Male", "Non-binary", "Unknown"],
            weights=[0.49, 0.49, 0.015, 0.005], k=1
        )[0]

        # Age distribution
        age_bucket = random.choices(
            ["pediatric", "young_adult", "middle", "senior"],
            weights=[0.05, 0.40, 0.35, 0.20], k=1
        )[0]
        if age_bucket == "pediatric":
            age = random.randint(0, 17)
        elif age_bucket == "young_adult":
            age = random.randint(18, 44)
        elif age_bucket == "middle":
            age = random.randint(45, 64)
        else:
            age = random.randint(65, 99)

        dob = date.today() - timedelta(days=age * 365 + random.randint(0, 364))

        # SSN (safe range, ~5% NULL)
        ssn = None if random.random() < 0.05 else f"{SAFE_SSN_PREFIX}-{random.randint(0, 9999):04d}"

        # Contact info (~15% missing email, ~5% missing phone)
        if random.random() < 0.15:
            email = None
        else:
            clean_first = first_name.lower().replace(" ", "").replace("'", "")
            clean_last = last_name.lower().replace(" ", "").replace("'", "")
            domain = random.choice(SAFE_EMAIL_DOMAINS)
            email = f"{clean_first}.{clean_last}@{domain}"
        phone = None if random.random() < 0.05 else f"{SAFE_PHONE_PREFIX}{random.randint(0, 99):02d}"

        # Address
        address = fake.street_address()
        city = fake.city()
        state = fake.state_abbr()
        zipcode = fake.zipcode()

        # Other demographics
        race = weighted_choice(RACE_OPTIONS)
        ethnicity = weighted_choice([
            ("Not Hispanic or Latino", 0.80),
            ("Hispanic or Latino", 0.18),
            ("Unknown", 0.02),
        ])
        language = weighted_choice(LANGUAGES)
        deceased = random.random() < 0.03

        patients.append({
            "patient_id": pid,
            "mrn": mrn,
            "first_name": first_name,
            "last_name": last_name,
            "dob": dob.isoformat(),
            "gender": gender,
            "race": race,
            "ethnicity": ethnicity,
            "ssn": ssn,
            "email": email,
            "phone": phone,
            "address_line1": address,
            "address_city": city,
            "address_state": state,
            "address_zip": zipcode,
            "preferred_language": language,
            "deceased_flag": deceased,
        })

    return patients


def output_csv(patients, filepath):
    df = pd.DataFrame(patients)
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write("# Generated by synth-data-gen | All data is fictional\n")
    df.to_csv(filepath, mode='a', index=False)
    print(f"✅ CSV written to {filepath} ({len(patients)} rows)")


def output_json(patients, filepath):
    output = {
        "_meta": {
            "generated_by": "synth-data-gen",
            "synthetic": True,
            "record_count": len(patients),
        },
        "data": patients,
    }
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(output, f, indent=2, ensure_ascii=False)
    print(f"✅ JSON written to {filepath} ({len(patients)} records)")


def output_sql(patients, filepath):
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write("-- Generated by synth-data-gen | All data is fictional\n")
        f.write("-- DO NOT use in production systems\n\n")
        f.write("INSERT INTO patients (patient_id, mrn, first_name, last_name, dob, "
                "gender, race, ethnicity, ssn, email, phone, address_line1, "
                "address_city, address_state, address_zip, preferred_language, "
                "deceased_flag)\nVALUES\n")

        for i, p in enumerate(patients):
            def sql_val(v):
                if v is None:
                    return "NULL"
                if isinstance(v, bool):
                    return "TRUE" if v else "FALSE"
                return "'" + str(v).replace("'", "''") + "'"

            vals = ", ".join([
                sql_val(p["patient_id"]), sql_val(p["mrn"]),
                sql_val(p["first_name"]), sql_val(p["last_name"]),
                sql_val(p["dob"]), sql_val(p["gender"]),
                sql_val(p["race"]), sql_val(p["ethnicity"]),
                sql_val(p["ssn"]), sql_val(p["email"]),
                sql_val(p["phone"]), sql_val(p["address_line1"]),
                sql_val(p["address_city"]), sql_val(p["address_state"]),
                sql_val(p["address_zip"]), sql_val(p["preferred_language"]),
                sql_val(p["deceased_flag"]),
            ])
            sep = ";" if i == len(patients) - 1 else ","
            f.write(f"    ({vals}){sep}\n")

    print(f"✅ SQL written to {filepath} ({len(patients)} rows)")


def main():
    parser = argparse.ArgumentParser(description="Generate synthetic patient data")
    parser.add_argument("--rows", "-n", type=int, default=100, help="Number of records")
    parser.add_argument("--seed", "-s", type=int, default=42, help="Random seed")
    parser.add_argument("--format", "-f", choices=["csv", "json", "sql"], default="csv")
    parser.add_argument("--output", "-o", default=None, help="Output file path")
    parser.add_argument("--validate", action="store_true", help="Run validation after generation")
    args = parser.parse_args()

    # Set seeds
    random.seed(args.seed)
    fake = Faker()
    Faker.seed(args.seed)

    print(f"Generating {args.rows} synthetic patients (seed={args.seed})...")
    patients = generate_patients(args.rows, fake, args.seed)

    # Output
    outfile = args.output or f"synthetic_patients.{args.format}"
    if args.format == "csv":
        output_csv(patients, outfile)
    elif args.format == "json":
        output_json(patients, outfile)
    elif args.format == "sql":
        output_sql(patients, outfile)

    # Optional validation
    if args.validate:
        print("\nRunning validation...")
        script_dir = Path(__file__).parent
        validator = script_dir / "validate_synthetic.py"
        if validator.exists():
            subprocess.run([sys.executable, str(validator), outfile])
        else:
            print("⚠️  Validator script not found. Skipping validation.")


if __name__ == "__main__":
    main()
